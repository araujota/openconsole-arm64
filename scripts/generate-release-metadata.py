"""Generate deterministic third-party notices, provenance, and CycloneDX SBOM."""
from __future__ import annotations
import hashlib,json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[1]
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def write(path,text):path.write_text(text,encoding="utf-8",newline="\n")
npm=[]
web_lock=ROOT/"web/package-lock.json"
if web_lock.is_file():
    lock=json.loads(web_lock.read_text())
    for path,meta in sorted(lock["packages"].items()):
        if not path:continue
        name=path.rsplit("node_modules/",1)[-1];license_id=meta.get("license")
        if not license_id and name=="memorystream":license_id="MIT"
        if not license_id:raise SystemExit(f"unresolved npm license: {name}")
        npm.append({"ecosystem":"npm","name":name,"version":meta.get("version","unknown"),
                    "license":license_id,"resolved":meta.get("resolved"),"integrity":meta.get("integrity")})
python=[
 {"ecosystem":"pypi","name":"capstone","version":"5.0.6","license":"BSD-3-Clause"},
 {"ecosystem":"pypi","name":"cryptography","version":"41.0.7","license":"Apache-2.0 OR BSD-3-Clause"},
 {"ecosystem":"pypi","name":"cffi","version":"2.1.1","license":"MIT"},
 {"ecosystem":"pypi","name":"pycparser","version":"3.12","license":"BSD-3-Clause"},
]
upstream=[
 {"name":"tianocore/edk2","revision":"0a503bc2f5bd37c7a5d39d0ba31008f446f0298d","license":"BSD-2-Clause-Patent","url":"https://github.com/tianocore/edk2"},
 {"name":"acidanthera/audk","revision":"dfd5516702b4911f1fc1919a429d637b456df913","license":"BSD-2-Clause-Patent","url":"https://github.com/acidanthera/audk"},
 {"name":"acidanthera/OpenCorePkg","revision":"78d5ff824992d5b227f842e34d8221eb8f31baf1","license":"BSD-3-Clause AND MIT","url":"https://github.com/acidanthera/OpenCorePkg"},
]
patches=[{"path":str(p.relative_to(ROOT)),"sha256":sha(p),"appliesTo":"OpenCorePkg" if "opencore" in str(p) else "edk2"}
         for p in sorted((ROOT/"patches").rglob("*.patch"))]
provenance={"schema":"openconsole.dependency-provenance.v1","npm":npm,"python":python,
            "firmwareUpstreams":upstream,"localPatches":patches}
write(ROOT/"dependency-provenance.json",json.dumps(provenance,indent=2,sort_keys=True)+"\n")
lines=["<!-- SPDX-License-Identifier: Apache-2.0 -->","# Third-party notices","",
 "Generated by `scripts/generate-release-metadata.py`. File-level upstream notices remain authoritative.","",
 "## Firmware source inputs","",
 "| Component | Revision | License | Upstream |","| --- | --- | --- | --- |"]
for item in upstream:lines.append(f"| {item['name']} | `{item['revision']}` | {item['license']} | {item['url']} |")
lines += ["","## Host analyzer dependencies","","| Package | Version | License |","| --- | --- | --- |"]
for item in python:lines.append(f"| {item['name']} | {item['version']} | {item['license']} |")
if npm:
    lines += ["","## Web dependencies (including transitive)","","| Package | Version | License |","| --- | --- | --- |"]
    for item in npm:lines.append(f"| {item['name']} | {item['version']} | {item['license']} |")
lines += ["","## Local patches","","| Patch | SHA-256 | Applies to |","| --- | --- | --- |"]
for item in patches:lines.append(f"| `{item['path']}` | `{item['sha256']}` | {item['appliesTo']} |")
write(ROOT/"THIRD_PARTY_NOTICES.md","\n".join(lines)+"\n")
components=[]
for item in npm+python:
    components.append({"type":"library","name":item["name"],"version":item["version"],
      "purl":f"pkg:{item['ecosystem']}/{item['name']}@{item['version']}","licenses":[{"expression":item["license"]}]})
for item in upstream:
    components.append({"type":"firmware","name":item["name"],"version":item["revision"],
      "licenses":[{"expression":item["license"]}],"externalReferences":[{"type":"vcs","url":item["url"]+"@"+item["revision"]}]})
for item in patches:components.append({"type":"file","name":item["path"],"hashes":[{"alg":"SHA-256","content":item["sha256"]}]})
bom={"bomFormat":"CycloneDX","specVersion":"1.5","serialNumber":"urn:uuid:1be958eb-b13a-5d7f-9cf0-4a9a254048f8","version":1,
 "metadata":{"component":{"type":"application","name":"openconsole","version":"0.1.0-dev","licenses":[{"expression":"Apache-2.0"}]}},
 "components":sorted(components,key=lambda x:(x["type"],x["name"],x.get("version","")))}
write(ROOT/"sbom.cdx.json",json.dumps(bom,indent=2,sort_keys=True)+"\n")
print(f"generated {len(npm)+len(python)+len(upstream)} dependency records and {len(patches)} patch records")
